
"""
Feature Engineering for Electricity Demand Prediction

This script loads the electricity dataset and creates a wide variety
of features to improve model performance. Features include:
- Time-based features (hour, day, month, weekday, etc.)
- Lag features
- Rolling statistics
- Cyclical encoding for periodicity
- Holiday flags
- Temperature/weather interactions (if available)
"""

import pandas as pd
import numpy as np
from pandas.tseries.holiday import USFederalHolidayCalendar as calendar


DATA_PATH = "Electricity_Dataset.csv"

df = pd.read_csv(DATA_PATH, parse_dates=['Datetime'])
df.sort_values('Datetime', inplace=True)
df.reset_index(drop=True, inplace=True)


df['hour'] = df['Datetime'].dt.hour
df['day'] = df['Datetime'].dt.day
df['month'] = df['Datetime'].dt.month
df['year'] = df['Datetime'].dt.year
df['weekday'] = df['Datetime'].dt.weekday
df['weekofyear'] = df['Datetime'].dt.isocalendar().week.astype(int)


df['hour_sin'] = np.sin(2 * np.pi * df['hour']/24)
df['hour_cos'] = np.cos(2 * np.pi * df['hour']/24)
df['day_sin'] = np.sin(2 * np.pi * df['day']/31)
df['day_cos'] = np.cos(2 * np.pi * df['day']/31)
df['month_sin'] = np.sin(2 * np.pi * df['month']/12)
df['month_cos'] = np.cos(2 * np.pi * df['month']/12)
df['weekday_sin'] = np.sin(2 * np.pi * df['weekday']/7)
df['weekday_cos'] = np.cos(2 * np.pi * df['weekday']/7)


for lag in [1, 2, 3, 6, 12, 24, 48, 72]:
    df[f'demand_lag_{lag}'] = df['Demand'].shift(lag)

for window in [3, 6, 12, 24, 48]:
    df[f'demand_roll_mean_{window}'] = df['Demand'].shift(1).rolling(window=window).mean()
    df[f'demand_roll_std_{window}'] = df['Demand'].shift(1).rolling(window=window).std()
    df[f'demand_roll_min_{window}'] = df['Demand'].shift(1).rolling(window=window).min()
    df[f'demand_roll_max_{window}'] = df['Demand'].shift(1).rolling(window=window).max()


cal = calendar()
holidays = cal.holidays(start=df['Datetime'].min(), end=df['Datetime'].max())
df['is_holiday'] = df['Datetime'].dt.date.isin(holidays.date).astype(int)


if 'Temperature' in df.columns:
    # Rolling temperature features
    for window in [3, 6, 12, 24]:
        df[f'temp_roll_mean_{window}'] = df['Temperature'].shift(1).rolling(window=window).mean()
        df[f'temp_roll_std_{window}'] = df['Temperature'].shift(1).rolling(window=window).std()
    # Interaction term
    df['temp_demand_interaction'] = df['Temperature'] * df['Demand']


df['is_weekend'] = (df['weekday'] >= 5).astype(int)

# Peak demand hours (example: 6 PM - 9 PM)
df['is_peak_hour'] = df['hour'].isin([18,19,20]).astype(int)

df['demand_diff_1'] = df['Demand'] - df['Demand'].shift(24)
# Percent change
df['demand_pct_change_1'] = df['Demand'].pct_change()
df['demand_pct_change_24'] = df['Demand'].pct_change(24)

# ------------------------------
# Fill NaNs generated by lags/rolling
# ------------------------------
df.fillna(method='bfill', inplace=True)
df.fillna(method='ffill', inplace=True)

# ------------------------------
# Save enhanced dataset
# ------------------------------
OUTPUT_PATH = "Electricity_Dataset_Features.csv"
df.to_csv(OUTPUT_PATH, index=False)
print(f"Feature engineering completed. Dataset saved to {OUTPUT_PATH}")
